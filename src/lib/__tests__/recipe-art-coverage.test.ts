import { describe, it, expect } from "vitest";
import { readFileSync, writeFileSync } from "node:fs";
import { CATALOG } from "@/lib/all-recipes";
import { getRecipeIllustration } from "@/lib/category-illustrations";

const DOC = "docs/recipe-art-needed.md";

const COLLECTION: Record<string, string> = {
  library: "library",
  kids: "kids",
  "plant-based-family": "plant-based",
  "matthew-kids": "matthew",
  "nz-au-family": "nz-au",
};

/** Render the "still needed" doc from the live resolver. */
function renderDoc(rows: typeof CATALOG): string {
  if (rows.length === 0) {
    return [
      "# Recipe illustrations",
      "",
      "Every recipe in the catalog now resolves to a picture: its own drawing, or a stand-in of the same",
      "kind of dish. Nothing falls through to the placeholder any more.",
      "",
      "To add art for a new recipe, draw it in the house style (soft watercolour and ink, three-quarter",
      "view, on a transparent background), save it as `public/images/recipes/meals/<id>.png`, add",
      '`"<id>": "/images/recipes/meals/<id>.png"` to `src/data/recipe-image-files.json`, then run',
      "`python scripts/make-recipe-images-transparent.py`. The recipe picks it up by its id.",
      "",
      "This file is regenerated by `recipe-art-coverage.test.ts`; edit the catalogue, not the list.",
      "",
    ].join("\n");
  }

  let md = `# Recipe illustrations still needed\n\n`;
  md += `These ${rows.length} recipes have no drawing of their own and no picture of the same kind of dish, so the\n`;
  md += `Recipes tab shows a quiet placeholder (a fork and knife) instead of a picture of something else.\n\n`;
  md += `To add one: draw it in the house style (soft watercolour and ink, three-quarter view, on a transparent\n`;
  md += "background), save it as `public/images/recipes/meals/<id>.png`, add `\"<id>\": \"/images/recipes/meals/<id>.png\"`\n";
  md += "to `src/data/recipe-image-files.json`, then run `python scripts/make-recipe-images-transparent.py`.\n";
  md += `The recipe picks it up by its id.\n\n`;
  md += `This file is regenerated by \`recipe-art-coverage.test.ts\`; edit the catalogue, not the list.\n\n`;
  md += `| id | Recipe | Collection | Main ingredients |\n| --- | --- | --- | --- |\n`;
  for (const e of rows) {
    const ingredients = e.recipe.ingredients.slice(0, 5).map((i) => i.replace(/\|/g, "/")).join(", ");
    md += `| \`${e.recipe.id}\` | ${e.recipe.name.replace(/\|/g, "/")} | ${COLLECTION[e.source] ?? e.source} | ${ingredients} |\n`;
  }
  return md;
}

/**
 * Guards the promise that a recipe card never shows a fork-and-knife placeholder
 * while a picture of the actual dish could exist. Regenerates the "still needed"
 * doc as a side effect so the doc can never drift from the resolver.
 */
describe("recipe art coverage", () => {
  const rows = CATALOG.filter((e) => getRecipeIllustration(e.recipe.name, e.recipe.id) === null);

  it("leaves no recipe on the placeholder", () => {
    expect(
      rows.map((e) => `${e.recipe.id}  [${e.source}]`),
      `${rows.length} of ${CATALOG.length} recipes show a placeholder`,
    ).toEqual([]);
  });

  it("keeps docs/recipe-art-needed.md in step with the resolver", () => {
    const expected = renderDoc(rows);
    if (readFileSync(DOC, "utf8") !== expected) {
      writeFileSync(DOC, expected);
      throw new Error(`${DOC} was stale and has been regenerated — commit the new version.`);
    }
    expect(true).toBe(true);
  });
});
