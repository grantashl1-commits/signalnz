/**
 * Builds stretch illustration prompts from the stretch catalogue.
 *
 * Reads  : src/data/stretch-illustrations.json
 * Writes : src/stretch-prompts.json                 (machine-readable, for the batch runner)
 *          src/assets/movement/PROMPTS-stretches.md  (human-readable paste sheet)
 *
 * Usage:
 *   node scripts/build-stretch-prompts.mjs
 *
 * These are the muscle-group images at public/images/stretches/, consumed by
 * src/components/movement/MuscleIllustration.tsx. They follow Style 1 in
 * src/assets/movement/STYLE.md (minimalist watercolour), the same style as the
 * strength & core set, and NOT the anatomical reformer style.
 *
 * Two deliberate departures from the letter of STYLE.md, both because these are
 * muscle-group illustrations rather than exercise poses:
 *  1. "Passive stretches get no muscle wash" is overridden — a soft dusty-rose
 *     wash on the target group is the whole point of the image. Set a catalogue
 *     entry's `wash` to null to omit it.
 *  2. The whole-body instruction leads the prompt. These were previously drawn as
 *     cropped anatomical diagrams; the figure must read head to feet.
 */
import { readFileSync, writeFileSync } from "node:fs";

const CATALOGUE = "src/data/stretch-illustrations.json";
const OUT_JSON = "src/stretch-prompts.json";
const OUT_MD = "src/assets/movement/PROMPTS-stretches.md";

const SHIPPED_DIR = "public/images/stretches";

/**
 * Whole-figure framing leads: image models weight early tokens most heavily, and
 * "wrong crop" is the failure this set is being redrawn to fix.
 */
const FRAMING = [
  "A hand-drawn, minimalist watercolour illustration of ONE woman shown WHOLE, head to feet.",
  "Her entire body fits comfortably inside the frame with clear white space above her head and below her feet — nothing is cropped at any edge, and this is never a close-up of a single limb, joint or muscle group.",
  "She is the only figure in the picture.",
].join(" ");

const STYLE_TAIL = [
  "Any muscle colour wash is painted directly onto her body, never as separate shapes, blobs or marks floating beside her.",
  "Show exactly one figure — never a sequence, a strip of stages or repeated poses.",
  "Warm earthy colours: terracotta, sage green, dusty rose.",
  "Gentle imperfect lines, thin hand-drawn pen outlines in warm brown.",
  "Plain flat white background with nothing else in the frame.",
  "No text, no labels, no letters, no arrows, no watermarks.",
].join(" ");

const buildPrompt = (entry) => {
  const figure =
    "A woman with a cream-coloured face, closed eyes, small nose and a calm neutral expression " +
    entry.pose +
    ". She wears a muted sage-green fitted sports top and sage-green shorts, so her arms and legs are bare.";

  const wash = entry.wash
    ? `A single soft dusty-rose watercolour wash marks only ${entry.wash}, painted as soft striations that follow the shape of the muscle on her bare skin. The wash never sits on her clothing, and it never appears as separate circles, round patches or blobs anywhere else on her body — in particular no pink patches on her shoulders, chest, neck, face, hands or feet.`
    : "No muscle wash at all — she is drawn in plain watercolour skin tones.";

  return [FRAMING, figure, wash, STYLE_TAIL].join("\n\n");
};

const catalogue = JSON.parse(readFileSync(CATALOGUE, "utf8"));

for (const entry of catalogue) {
  if (!entry.pose || entry.pose.length < 40) {
    console.error(`Entry "${entry.id}" needs a detailed pose.`);
    process.exit(1);
  }
}

const out = catalogue.map((entry) => ({
  id: entry.id,
  name: entry.name,
  target: entry.target,
  outputFile: `${SHIPPED_DIR}/${entry.id}.png`,
  prompt: buildPrompt(entry),
}));

writeFileSync(OUT_JSON, JSON.stringify(out, null, 2) + "\n");

// ─── human-readable paste sheet ─────────────────────────────────────────
let md = `# Stretch Illustration Prompts\n\n`;
md += `Generated by \`scripts/build-stretch-prompts.mjs\` from \`src/data/stretch-illustrations.json\`.\n`;
md += `Do not edit by hand — edit the catalogue and re-run.\n\n`;
md += `**${out.length} images** for \`public/images/stretches/\`, shown by\n`;
md += `\`src/components/movement/MuscleIllustration.tsx\`.\n\n`;
md += `Style 1 in [\`STYLE.md\`](./STYLE.md) — minimalist watercolour, the same style as the\n`;
md += `strength & core set, **not** the anatomical reformer style.\n\n`;
md += `> Two deliberate departures from STYLE.md: passive stretches do get a soft\n`;
md += `> dusty-rose wash (that is what identifies the target group), and the whole-body\n`;
md += `> framing leads the prompt because these were previously cropped too tight.\n\n`;
md += `---\n\n`;

md += `## How a prompt is assembled\n\n`;
const FENCE = "```";
md += FENCE + "text\n" + FRAMING + "\n\nA woman with a cream-coloured face ... <pose>.\n\n";
md += "<wash line>\n\n" + STYLE_TAIL + "\n" + FENCE + "\n\n---\n\n";

md += `## The images\n\n`;
md += `| # | File | Stretch | Target |\n|--:|---|---|---|\n`;
out.forEach((o, i) => {
  md += `| ${i + 1} | \`${o.id}.png\` | ${o.name} | ${o.target} |\n`;
});
md += `\n---\n\n`;

md += `## Per-image prompts\n`;
for (const o of out) {
  md += `\n### ${o.name}\n\n`;
  md += `**File:** \`${SHIPPED_DIR}/${o.id}.png\` · **Target:** ${o.target}\n\n`;
  md += "```text\n" + o.prompt + "\n```\n\n";
}

writeFileSync(OUT_MD, md);

console.log(`Wrote ${out.length} prompts -> ${OUT_JSON}`);
console.log(`Wrote prompt sheet  -> ${OUT_MD}`);
