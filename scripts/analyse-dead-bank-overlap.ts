/**
 * Cross-bank duplicate analysis: which recipes in the orphaned banks actually
 * duplicate a live recipe, and which are unique content sitting unreachable.
 *
 * This is the distinction that decides what is safe to delete: a dead-bank
 * recipe that matches a live one is a true duplicate; a dead-bank recipe with no
 * live counterpart is unique content that someone may still want to wire up.
 *
 *   npx tsx scripts/analyse-dead-bank-overlap.ts
 */
import { ALL_RECIPES } from "@/lib/recipe-index";

type R = { id: string; name: string; ingredients?: string[] };

const BANKS = [
  "baking-recipes", "bowl-meal-recipes", "doctors-kitchen-recipes", "extra-batch-recipes",
  "glucose-revolution-recipes", "how-not-to-diet-recipes", "meal-plan-recipes",
  "pdf-expanded-recipes", "pdf-library-recipes", "pdf-recipes", "plant-powered-plus-recipes",
  "plant-powered-recipes", "protein-15-recipes", "snack-dessert-recipes",
  "storage-pdf-recipes", "tcm-ayurveda-recipes", "vegan-basics-recipes",
];

const norm = (s: string) =>
  s.toLowerCase().replace(/&/g, "and").replace(/[''`]/g, "").replace(/[^a-z0-9]+/g, " ").trim();

const STOP = new Set(["with", "and", "the", "a", "an", "of", "in", "on", "for", "to"]);
const kw = (s: string) => norm(s).split(" ").filter((w) => w.length > 1 && !STOP.has(w));
const key = (s: string) => kw(s).sort().join(" ");

function overlap(a: string[] = [], b: string[] = []): number {
  const setOf = (l: string[]) => new Set(l.flatMap((x) => kw(x)));
  const A = setOf(a);
  const B = setOf(b);
  if (!A.size || !B.size) return 0;
  let i = 0;
  for (const x of A) if (B.has(x)) i++;
  return i / (A.size + B.size - i);
}

const live: R[] = ALL_RECIPES as R[];
const liveByName = new Map<string, R[]>();
const liveByKey = new Map<string, R[]>();
for (const r of live) {
  for (const [m, k] of [[liveByName, norm(r.name)], [liveByKey, key(r.name)]] as const) {
    const arr = m.get(k);
    if (arr) arr.push(r);
    else m.set(k, [r]);
  }
}

type Finding = { bank: string; recipe: R; reason: string; match?: R; score?: number };

const exact: Finding[] = [];
const fuzzy: Finding[] = [];
const unique: { bank: string; recipe: R }[] = [];
const failed: string[] = [];

for (const bank of BANKS) {
  let mod: Record<string, unknown>;
  try {
    mod = await import(`@/data/${bank}`);
  } catch {
    failed.push(bank);
    continue;
  }
  // Take the first exported array of objects that look like recipes.
  const arr = (Object.values(mod).find(
    (v) => Array.isArray(v) && v.length && typeof v[0] === "object" && "name" in (v[0] as object),
  ) as R[]) ?? [];

  for (const r of arr) {
    if (!r?.name) continue;
    const hitExact = liveByName.get(norm(r.name)) ?? liveByKey.get(key(r.name));
    if (hitExact?.length) {
      exact.push({ bank, recipe: r, reason: "same name as a live recipe", match: hitExact[0] });
      continue;
    }
    // best ingredient-overlap candidate
    let best: R | undefined;
    let bestScore = 0;
    for (const l of live) {
      const s = overlap(r.ingredients, l.ingredients);
      if (s > bestScore) {
        bestScore = s;
        best = l;
      }
    }
    if (bestScore >= 0.8 && best) {
      fuzzy.push({ bank, recipe: r, reason: `${(bestScore * 100).toFixed(0)}% ingredient overlap`, match: best, score: bestScore });
    } else {
      unique.push({ bank, recipe: r });
    }
  }
}

const byBank = new Map<string, { total: number; exact: number; fuzzy: number; unique: number }>();
for (const b of BANKS) byBank.set(b, { total: 0, exact: 0, fuzzy: 0, unique: 0 });
for (const f of exact) byBank.get(f.bank)!.exact++;
for (const f of fuzzy) byBank.get(f.bank)!.fuzzy++;
for (const u of unique) byBank.get(u.bank)!.unique++;

const L: string[] = [];
L.push(`# Orphaned recipe banks — duplicate vs unique\n`);
L.push(`Generated by \`scripts/analyse-dead-bank-overlap.ts\`.\n`);
L.push(`Live library: **${live.length}** recipes (NOURISH_RECIPES + SIGNAL_REWRITES).\n`);
if (failed.length) L.push(`Could not import: ${failed.join(", ")}\n`);

L.push(`## Per bank\n`);
L.push(`| Bank | Recipes | Same name as live | Ingredient-identical | Unique |`);
L.push(`|---|--:|--:|--:|--:|`);
let T = 0, E = 0, F = 0, U = 0;
for (const b of BANKS) {
  const s = byBank.get(b)!;
  const total = s.exact + s.fuzzy + s.unique;
  T += total; E += s.exact; F += s.fuzzy; U += s.unique;
  L.push(`| ${b} | ${total} | ${s.exact} | ${s.fuzzy} | ${s.unique} |`);
}
L.push(`| **TOTAL** | **${T}** | **${E}** | **${F}** | **${U}** |\n`);
L.push(`- **${E}** are the same dish by name → true duplicates.\n`);
L.push(`- **${F}** are different names but >=80% identical ingredients → near duplicates.\n`);
L.push(`- **${U}** have no live counterpart → unique content, currently unreachable.\n`);

L.push(`## Same-name duplicates (${exact.length})\n`);
for (const f of exact) L.push(`- \`${f.bank}\` ${f.recipe.name}  =  live ${f.match!.id}`);

L.push(`\n## Near duplicates (${fuzzy.length})\n`);
for (const f of fuzzy) L.push(`- \`${f.bank}\` ${f.recipe.name}  ~  live ${f.match!.id} (${f.reason})`);

L.push(`\n## Unique content, unreachable (${unique.length})\n`);
for (const u of unique) L.push(`- \`${u.bank}\` ${u.recipe.name}`);

import { writeFileSync } from "node:fs";
writeFileSync("handoff/dead-bank-overlap.md", L.join("\n"));

console.log(`live: ${live.length}`);
if (failed.length) console.log(`failed to import: ${failed.join(", ")}`);
console.log(`orphan recipes scanned: ${T}`);
console.log(`  same name as live:      ${E}`);
console.log(`  >=80% ingredient match: ${F}`);
console.log(`  unique / unreachable:   ${U}`);
console.log(`\nwrote handoff/dead-bank-overlap.md`);
